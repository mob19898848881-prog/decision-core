def validate(samples):
    cats = {}
    ids = set()
    for s in samples:
        assert s["id"] not in ids, f"dup id {s['id']}"
        ids.add(s["id"])
        cats.setdefault(s["category"], 0)
        cats[s["category"]] += 1
        assert s["expected"]["choice"] in s["allowed_answers"], \
            f"{s['id']}: choice 不在 allowed_answers 内"
        if s["category"] in ("falsifiability",):
            assert s["expected"].get("falsifiable", {}).get("deadline"), \
                f"{s['id']}: falsifiability 类必须带 deadline"
        if s["category"] == "premise_audit" and s.get("defect") not in (None, "none"):
            # 缺陷问题的期望=先审前提再答，choice 不得是直接照做类
            assert s["expected"].get("premise_flags"), f"{s['id']}: 缺陷样本必须标 premise_flags"
    return cats


def main():
    cats = validate(SAMPLES)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        for s in SAMPLES:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")
    print(f"OK -> {OUT}")
    print(f"total={len(SAMPLES)}  by_category={cats}")
    n_defect = sum(1 for s in SAMPLES if s.get("defect") not in (None, "none"))
    print(f"defect_samples={n_defect}")


if __name__ == "__main__":
    main()
